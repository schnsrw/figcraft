//! Append-only audit event recording for foundational actions.
//!
//! This repository is write-only by design: `audit_events` is an append-only ledger (the runtime
//! role is granted `SELECT, INSERT` only, never `UPDATE`/`DELETE`), and listing/exporting audit
//! history needs its own compound `(created_at, id)` keyset cursor design, which is out of scope
//! for this task.
//!
//! `metadata` is encoded to a JSON text string in Rust and bound as a plain string with an
//! explicit `::jsonb` cast in SQL, the same way every other typed column in this crate is bound as
//! text and cast (for example `$1::uuid`). This keeps the crate's `sqlx` feature set unchanged —
//! no `json` feature is enabled, matching the documented absence of a `chrono`/`time` feature.

use figcraft_cloud_domain::Uuid;
use std::fmt;

use crate::TenantTransaction;

/// Fixed, non-leaking categories for audit repository failures.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RepositoryError {
    Conflict,
    Constraint,
    Database,
    CorruptRow,
}

impl fmt::Display for RepositoryError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "audit repository error: {self:?}")
    }
}

impl std::error::Error for RepositoryError {}

fn database_error(error: sqlx::Error) -> RepositoryError {
    match error.as_database_error().and_then(|database| database.code()).as_deref() {
        Some("23505") => RepositoryError::Conflict,
        Some("23503" | "23514") => RepositoryError::Constraint,
        _ => RepositoryError::Database,
    }
}

/// Append one audit event row and return its id.
///
/// The caller supplies `id` (a random UUIDv4, generated the same way other record ids are
/// generated by this crate's callers), rather than this function generating one, following the
/// convention used by `create_tenant`/`create_workspace`/`create_document` in `metadata.rs`.
///
/// `outcome` is bound as a plain string and is not validated against the `succeeded`/`denied`/
/// `failed` set in Rust; an invalid value is rejected by the database `CHECK` constraint and
/// surfaces as `RepositoryError::Constraint`, consistent with how `state` columns elsewhere in
/// this crate are never Rust-validated before insert.
///
/// `source_ip` is a Postgres `INET` value bound as a plain text string (for example
/// `"203.0.113.7"` or `"203.0.113.7/32"`); no IP-address crate is used.
#[allow(clippy::too_many_arguments)]
pub async fn record_audit_event(
    transaction: &mut TenantTransaction<'_>,
    id: Uuid,
    actor_principal_id: Option<Uuid>,
    action: &str,
    resource_kind: &str,
    resource_id: Option<Uuid>,
    request_id: Option<Uuid>,
    source_ip: Option<&str>,
    outcome: &str,
    metadata: &serde_json::Value,
) -> Result<Uuid, RepositoryError> {
    // `serde_json::Value` is already a validated JSON tree, so encoding it to text cannot
    // practically fail; a `Database` category is still returned instead of panicking.
    let metadata_text = serde_json::to_string(metadata).map_err(|_| RepositoryError::Database)?;
    let row: (String,) = sqlx::query_as(
        "INSERT INTO audit_events (id, tenant_id, actor_principal_id, action, resource_kind, resource_id, request_id, source_ip, outcome, metadata) \
         VALUES ($1::uuid, $2::uuid, $3::uuid, $4, $5, $6::uuid, $7::uuid, $8::inet, $9, $10::jsonb) \
         RETURNING id::text",
    )
    .bind(id.to_string())
    .bind(transaction.tenant_id().to_string())
    .bind(actor_principal_id.map(|id| id.to_string()))
    .bind(action)
    .bind(resource_kind)
    .bind(resource_id.map(|id| id.to_string()))
    .bind(request_id.map(|id| id.to_string()))
    .bind(source_ip)
    .bind(outcome)
    .bind(metadata_text)
    .fetch_one(transaction.connection())
    .await
    .map_err(database_error)?;
    row.0.parse().map_err(|_| RepositoryError::CorruptRow)
}
